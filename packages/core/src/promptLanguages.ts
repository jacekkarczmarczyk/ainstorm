import type { TaskStatus } from './model.ts';

/**
 * Sentences of the prompts copied from the UI into a session, one set per language. Placeholders in braces are filled
 * by buildPrompt with values it has already made safe (quoted, one line); the logic of each prompt stays in prompts.ts.
 */
export interface PromptPhrases {
  /** Native name, for the language picker */
  name: string;
  /** Quotation marks around task titles */
  quotes: readonly [string, string];
  status: Record<TaskStatus, string>;
  statusChanged: string;
  deleted: string;
  deletedWithSubtasks: string;
  dropped: string;
  run: string;
  pause: string;
  goAhead: string;
  focus: string;
  promote: string;
  moved: string;
  under: string;
  topLevel: string;
  wasUnder: string;
  wasTopLevel: string;
  answer: string;
  recheck: string;
  runManyIntro: string;
  runManyOutro: string;
  commitSet: string;
  commitRemoved: string;
  issueCreate: string;
  issueClose: string;
  statusMany: string;
  statusManyItem: string;
  statusManyDropped: string;
  statusManyOther: string;
  moveMany: string;
  moveManyOutro: string;
  typeMany: string;
  areaAdded: string;
  areaRemoved: string;
  decideYes: string;
  decideNo: string;
  /** The user's own answer to a decision, quoted */
  decideAnswer: string;
  note: string;
  created: string;
  createdRun: string;
  edited: string;
}

